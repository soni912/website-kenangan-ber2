let activePhotoIndex = 0;
function renderGallery() {
  const grid = document.getElementById("galleryGrid");
  grid.innerHTML = galleryPhotos
    .map(
      (photo, index) => `
    <button class="gallery-item reveal" type="button" data-photo-index="${index}" aria-label="Lihat ${photo.title}">
      <img src="${photo.src}" alt="${photo.title}" loading="lazy" onerror="this.src='https://images.unsplash.com/photo-1516589178581-6cd7833ae3b2?auto=format&fit=crop&w=700&q=80'">
      <span class="gallery-caption"><b>${photo.title}</b><small>${photo.date} · ${photo.caption}</small></span>
    </button>`,
    )
    .join("");
  grid
    .querySelectorAll(".gallery-item")
    .forEach((button) =>
      button.addEventListener("click", () =>
        openLightbox(Number(button.dataset.photoIndex)),
      ),
    );
  observeReveals();
}
function openLightbox(index) {
  activePhotoIndex = index;
  const photo = galleryPhotos[index];
  document.getElementById("lightboxImage").src = photo.src;
  document.getElementById("lightboxImage").alt = photo.title;
  document.getElementById("lightboxCaption").textContent =
    `${photo.title} — ${photo.date} · ${photo.caption}`;
  document.getElementById("lightbox").classList.remove("hidden");
  document.body.style.overflow = "hidden";
}
function moveLightbox(direction) {
  openLightbox(
    (activePhotoIndex + direction + galleryPhotos.length) %
      galleryPhotos.length,
  );
}
function closeLightbox() {
  document.getElementById("lightbox").classList.add("hidden");
  document.body.style.overflow = "";
}

